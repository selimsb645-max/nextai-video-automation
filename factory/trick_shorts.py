"""Wildlife 'trick' Shorts producer (owner request 2026-11-14).

Owner shared a Google Doc master prompt ("Fack birds trick"): a 9:16, 10-second
photorealistic clip of a bird faking death, then grabbing a fish. That clip has
to be generated by hand in Muse AI / Google Flow - neither has an API, so no
GitHub runner can produce it. This module produces the machine-made version of
the same format every day, unattended:

    real free wildlife footage (Pixabay Content Licence)
      -> 5-beat deception story (tension, approach, catch, reveal)
      -> Kokoro narration + burned key-phrase captions
      -> 1080x1920 render on the existing factory engine
      -> scheduled YouTube Short

The full paste-ready master prompts live in factory/trick_library.json so the
owner can still generate the AI version by hand whenever he wants.

Usage (workflow calls this):
    python3 factory/trick_shorts.py --selftest     # render, never upload
    python3 factory/trick_shorts.py                # schedule a real Short
    python3 factory/trick_shorts.py --trick trick_octopus_rock
"""
from __future__ import annotations

