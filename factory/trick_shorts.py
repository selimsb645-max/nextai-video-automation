ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACT = os.path.join(ROOT, "factory")
# Exactly how actions/runner.py loads it: the factory *directory* on the path,
# so ``factory`` resolves to factory/factory.py (module), not a namespace package.
sys.path.insert(0, FACT)
import factory as F  # noqa: E402  (production engine: voice, render, upload)


BASE = F.BASE
LIB_F = os.path.join(BASE, "trick_library.json")
STATE_F = os.path.join(BASE, "trick_state.json")
USED_F = os.path.join(BASE, "footage", "_trick_used.json")
CLIP_DIR = os.path.join(BASE, "footage", "tricks")
REPORT_DIR = os.path.join(ROOT, "actions", "reports")
UA = F.UA


def log(msg):
    print("[" + time.strftime("%H:%M:%S") + "] " + str(msg), flush=True)


def _load(path, default):
    try:
        with open(path) as fh:
            return json.load(fh)
    except Exception:
        return default


def media_duration(path):
    try:
        out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                             "format=duration", "-of", "csv=p=0", path],
                            capture_output=True, text=True).stdout.strip()
        return float(out or 0)
    except Exception:
        return 0.0


def _save(path, doc):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(doc, fh, indent=1, ensure_ascii=False)


# ---------------------------------------------------------------- topic choice
def pick_trick(lib, state, forced=""):
    entries = lib["entries"]
    by_id = {e["id"]: e for e in entries}
    if forced:
        if forced not in by_id:
            raise SystemExit("unknown trick id: " + forced)
        return by_id[forced]
    done = state.setdefault("done", {})
    for e in entries:                       # first never-used topic wins
        if e["id"] not in done:
            return e
    # every topic used at least once: restart the cycle with the oldest one
    order = sorted(entries, key=lambda e: done.get(e["id"], {}).get("date", ""))
    log("trick library exhausted - restarting the cycle with " + order[0]["id"])
    return order[0]


# ------------------------------------------------------------------- footage
def _rel_score(query, hit):
    q = {w for w in re.split(r"[^a-z0-9]+", query.lower()) if len(w) >= 3}
    tags = hit.get("tags") or ""
    if not isinstance(tags, str):
        tags = " ".join(tags)
    blob = (tags + " " + (hit.get("pageURL") or "")).lower()
    return len(q & {w for w in re.split(r"[^a-z0-9]+", blob) if len(w) >= 3})


def search_pixabay(query, used):
    if not F.PIXABAY_KEY:
        raise SystemExit("PIXABAY_API_KEY missing - cannot fetch footage")
    url = "https://pixabay.com/api/videos/?" + urllib.parse.urlencode({
        "key": F.PIXABAY_KEY, "q": query, "per_page": 20,
        "video_type": "film", "safesearch": "true", "order": "popular"})
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    try:
        doc = json.load(urllib.request.urlopen(req, timeout=40))
    except Exception as ex:
        log("pixabay search failed for %r: %s" % (query, str(ex)[:120]))
        return []
    out = []
    for h in doc.get("hits", []):
        if str(h.get("id")) in used:
            continue
        vids = h.get("videos") or {}
        best = vids.get("large") or vids.get("medium") or vids.get("small")
        if not best or not best.get("url"):
            continue
        if float(h.get("duration") or 0) < 3:
            continue
        out.append((h, best))
    out.sort(key=lambda p: -(_rel_score(query, p[0]) * 1_000_000
                             + (p[0].get("views") or 0)))
    return out


def download(url, dest):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=240) as r, open(dest, "wb") as fh:
        while True:
            chunk = r.read(1 << 22)
            if not chunk:
                break
            fh.write(chunk)
    dur = float(subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", dest], capture_output=True, text=True).stdout.strip() or 0)
    return dur


def fetch_clips(topic, used):
    """One distinct clip per beat. A beat we cannot source is dropped (the
    narration is rebuilt from what survived) rather than shipping a wrong shot."""
    os.makedirs(CLIP_DIR, exist_ok=True)
    pairs = []
    for i, beat in enumerate(topic["beats"]):
        queries = [beat["q"]]
        for extra in (beat["q"].split()[0], "wildlife animal"):
            if extra not in queries:
                queries.append(extra)
        got = None
        for q in queries:
            for hit, best in search_pixabay(q, used)[:6]:
                dest = os.path.join(CLIP_DIR, "%s_b%d.mp4" % (topic["id"], i))
                try:
                    dur = download(best["url"], dest)
                except Exception as ex:
                    log("  download failed (%r): %s" % (q, str(ex)[:100]))
                    continue
                if dur < 3:
                    continue
                used.add(str(hit["id"]))
                got = {"file": "tricks/" + os.path.basename(dest), "dur": dur,
                       "q": q, "url": best["url"], "id": hit["id"],
                       "page": hit.get("pageURL", ""), "creator": hit.get("user", "")}
                log("  beat %d <- %r (%s, %.1fs)" % (i, q, hit["id"], dur))
                break
            if got:
                break
        if got:
            pairs.append((beat, got))
        else:
            log("  beat %d: NO FOOTAGE for %r - dropping this beat" % (i, beat["q"]))
    if len(pairs) < 3:
        raise SystemExit("FOOTAGE_INSUFFICIENT: only %d/%d beats sourced"
                         % (len(pairs), len(topic["beats"])))
    return pairs


# --------------------------------------------------------------- entry + thumb
def build_entry(topic, pairs, policy):
    beats = [{"t": b["t"], "q": b["q"]} for b, _c in pairs]
    return {
        "id": "%s_%s" % (topic["id"], time.strftime("%Y%m%d")),
        "topic_id": topic["id"],
        "title": topic["title"],
        "kind": "short",
        "headline": "",              # no poster overlay: keep the footage clean
        "beats": beats,
        "narration": " ".join(b["t"] for b in beats),
        "tags": list(topic["tags"]),
        "description": topic["description"].strip() + "\n\n#Shorts",
        "categoryId": "15",          # Pets & Animals
        "madeForKids": False,
        "content_policy_version": policy["version"],
        "content_pillar": "wildlife_tricks",
        "scope_reviewed": True,
        "verified_sources": [
            "https://pixabay.com/ (Pixabay Content Licence, free commercial use)",
            "owner master-prompt doc 'Fack birds trick' shared 2026-11-14"],
        "demand_evidence": ("owner request 2026-11-14: publish the 'dead bird trick' "
                            "format as daily Shorts"),
        "seed": sum(ord(c) for c in topic["id"]),
    }


def make_thumb(topic, pair, workdir):
    """Vertical still from the first clip + the headline, saved as thumb.jpg."""
    clip_file = os.path.join(F.FOOTAGE, pair[1]["file"])
    raw = os.path.join(workdir, "thumb_raw.jpg")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", "1.0",
                    "-i", clip_file, "-frames:v", "1", "-vf",
                    "scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920",
                    raw], capture_output=True, text=True)
    if not os.path.exists(raw):
        return False
    try:
        from PIL import Image, ImageDraw, ImageFont
    except Exception:
        return False
    font_path = next((p for p in [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"] if os.path.exists(p)), None)
    if not font_path:
        return False
    im = Image.open(raw).convert("RGB")
    draw = ImageDraw.Draw(im)
    text = (topic.get("headline") or topic["title"]).upper()
    size = 118
    while size > 54:
        font = ImageFont.truetype(font_path, size)
        if draw.textlength(text, font=font) <= 940:
            break
        size -= 6
    font = ImageFont.truetype(font_path, size)
    w = draw.textlength(text, font=font)
    x, y = (1080 - w) / 2, 1180
    draw.text((x, y), text, font=font, fill="white",
              stroke_width=max(6, size // 12), stroke_fill="black")
    im.save(os.path.join(workdir, "thumb.jpg"), quality=92)
    return True



# ------------------------------------------------------------------ scheduling
def pick_slot():
    """Book the next free Short slot.

    The main factory already books 1-2 of the three daily Short slots about a
    day ahead, so the strict 1-22h window in next_bd_slot() is often closed for
    this producer. Fall back to the earliest configured slot that is still in
    the future and not reserved in published_log, and let upload() accept it
    with allow_override (the caller has already proven it is a real slot time).
    Returns (publish_at_iso, slot_local, override_needed).
    """
    try:
        return F.next_bd_slot("short") + (False,)
    except SystemExit as ex:
        log("default window closed (%s) - picking the next free slot" % str(ex)[:70])

    import datetime as _dt
    from zoneinfo import ZoneInfo
    cfg = _load(os.path.join(BASE, "content_policy.json"), {}).get("schedules", {})
    tz = ZoneInfo(cfg.get("timezone", "Asia/Dhaka"))
    reserved = set()
    for row in _load(os.path.join(BASE, "published_log.json"), []):
        if row.get("kind") == "short" and row.get("scheduled_for"):
            reserved.add(row["scheduled_for"])
    now = _dt.datetime.now(_dt.timezone.utc)
    for day in range(4):
        for hhmm in sorted(cfg.get("slots", {}).get("short", ["18:30"])):
            hh, mm = [int(x) for x in hhmm.split(":")]
            cand = (now.astimezone(tz) + _dt.timedelta(days=day)).replace(
                hour=hh, minute=mm, second=0, microsecond=0)
            iso = cand.astimezone(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            if (cand.astimezone(_dt.timezone.utc) - now) < _dt.timedelta(hours=2):
                continue
            if iso in reserved:
                continue
            log("next free slot: %s (%s)" % (iso, hhmm + " " + cfg.get("timezone", "")))
            return iso, cand, True
    raise SystemExit("NO_FREE_SHORT_SLOT: every configured slot in the next 4 days is booked")


# ---------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true", help="render but never upload")
    ap.add_argument("--trick", default="", help="force one trick id")
    args = ap.parse_args()

    lib = _load(LIB_F, None)
    if not lib or not lib.get("entries"):
        raise SystemExit("trick library missing or empty: " + LIB_F)
    state = _load(STATE_F, {"done": {}})
    used_doc = _load(USED_F, {"ids": []})
    used = set(used_doc.get("ids", []))

    policy = _load(os.path.join(BASE, "content_policy.json"), {})
    if "wildlife_tricks" not in (policy.get("allowed_pillars") or []):
        raise SystemExit("CONTENT_SCOPE_BLOCKED: add 'wildlife_tricks' to "
                         "content_policy.json allowed_pillars first")

    topic = pick_trick(lib, state, args.trick)
    log("=== trick short: %s (%s)" % (topic["title"], topic["id"]))

    pairs = fetch_clips(topic, used)
    _save(USED_F, {"ids": sorted(used)})
    e = build_entry(topic, pairs, policy)
    if not F.content_eligible(e):
        raise SystemExit("CONTENT_SCOPE_BLOCKED: " + e["id"])

    today = time.strftime("%Y-%m-%d")
    workdir = os.path.join(F.RUNS, e["id"])
    os.makedirs(workdir, exist_ok=True)
    log("workdir: " + workdir)

    audio = F.gen_voice(e, workdir)
    clips = [(c, len(b["t"].split())) for b, c in pairs]
    mp4 = F.render(e, workdir, clips, audio)
    log("render OK: " + mp4)
    make_thumb(topic, pairs[0], workdir)

    vid = None
    publish_at, slot, override = pick_slot()
    if args.selftest:
        log("selftest: would book slot %s (%s) - NOT uploading" % (publish_at, slot))
    else:
        if media_duration(mp4) > 61:
            raise SystemExit("SHORT_TOO_LONG")
        vid = F.upload(e, mp4, publish_at, allow_override=override)
        F.note_published(e, vid, "short", publish_at)
        log("uploaded videoId=%s scheduledFor=%s (%s)" % (vid, publish_at, slot))
        try:
            if F.set_thumbnail(vid, workdir):
                log("thumbnail: set")
        except Exception as ex:
            log("thumbnail failed (continuing): " + str(ex)[:120])

    # A selftest must never burn a topic: only a real upload marks it used.
    if not args.selftest:
        state.setdefault("done", {})[topic["id"]] = {
            "date": today, "videoId": vid, "scheduled_for": publish_at}
        _save(STATE_F, state)

    os.makedirs(REPORT_DIR, exist_ok=True)
    report = os.path.join(REPORT_DIR, "trick_%s.json" % time.strftime("%Y%m%d_%H%M"))
    _save(report, {"trick": topic["id"], "title": e["title"], "videoId": vid,
                   "scheduled_for": publish_at, "slot": str(slot),
                   "beats": len(pairs), "selftest": bool(args.selftest),
                   "clips": [{"file": c["file"], "query": c["q"],
                              "page": c.get("page", ""), "dur": round(c["dur"], 2)}
                             for _b, c in pairs]})
    log("report: " + report)
    print("TRICK_SHORT_RESULT " + json.dumps({"videoId": vid,
                                              "scheduled_for": publish_at,
                                              "trick": topic["id"]}), flush=True)


if __name__ == "__main__":
    main()
