#!/usr/bin/env python3
"""Mirror the reference channel's topics into OUR production queue.

Owner rule (2026-11-01): "ওই চ্যানেলে যে ভিডিও আপলোড হবে আমাদের চ্যানেলে ওই ভিডিও
আপলোড হবে — ওরা তৈরি করবে আমাদেরটা আমরা তৈরি করব". So: when AI Revolution
(@airevolutionx) publishes on a topic, we publish OUR OWN video on the same
topic. We never download, re-upload or re-use their footage or script - only the
subject is shared, and every word/frame of ours is generated by our pipeline.

Reads the channel's public RSS feed, converts new uploads into `pending`
library entries with truthful demand evidence, and records what it has seen.

  python3 factory/reference_mirror.py            # add new topics
  python3 factory/reference_mirror.py --dry-run  # show what would be added
"""
import argparse
import datetime as dt
import json
import os
import re
import urllib.request
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
LIBRARY = os.path.join(HERE, "library.json")
SEEN = os.path.join(HERE, "reference_mirror.json")
CHANNEL_ID = "UC5l7RouTQ60oUjLjt1Nh-UQ"          # @airevolutionx "AI Revolution"
FEED = f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"
UA = {"User-Agent": "Mozilla/5.0 (compatible; nextai-mirror/1.0)"}

NS = {"a": "http://www.w3.org/2005/Atom", "yt": "http://www.youtube.com/xml/schemas/2015"}

# hype that belongs to their title, not to the subject
HYPE = [
    r"^it'?s over\W*", r"^it'?s happening\W*", r"^breaking\W*", r"^finally\W*",
    r"^this is (?:it|crazy|insane)\W*", r"just (?:got|started|smashed|dropped)\b",
    r"\bway better than (?:it )?should be\b", r"\bno one (?:saw|expected)\b",
    r"[!]{1,}", r"\bbasically\b", r"\bactually\b",
]


def clean_topic(title):
    """Their headline -> a neutral subject we can research and script ourselves."""
    t = re.sub(r"\s*[\(\[][^)\]]{0,60}[\)\]]\s*", " ", title)      # drop (10x cheaper...)
    for pat in HYPE:
        t = re.sub(pat, " ", t, flags=re.I)
    t = re.sub(r"\s{2,}", " ", t).strip(" -–—:|.,")
    # a dangling copula/aux reads as a broken headline once the hype is gone
    t = re.sub(r"\s+(?:is|are|was|were|will|can|could|may|might|has|have|had|"
               r"and|with|of|the|a|an|again|now|just)$", "", t, flags=re.I)
    t = re.sub(r"^(?:AI|The|This)\s+(?=(?:AI|Biggest|First)\b)", "", t, flags=re.I)
    return t.strip(" -–—:|.,") or title.strip()


def slug(topic, date):
    s = re.sub(r"[^a-z0-9]+", "_", topic.lower()).strip("_")[:58]
    return f"ref_{date.replace('-', '_')}_{s}"


def fetch_feed(limit=15):
    req = urllib.request.Request(FEED, headers=UA)
    root = ET.fromstring(urllib.request.urlopen(req, timeout=45).read())
    out = []
    for e in root.findall("a:entry", NS)[:limit]:
        vid = e.findtext("yt:videoId", default="", namespaces=NS)
        ttl = (e.findtext("a:title", default="", namespaces=NS) or "").strip()
        pub = (e.findtext("a:published", default="", namespaces=NS) or "")[:10]
        if vid and ttl:
            out.append({"videoId": vid, "title": ttl, "published": pub,
                        "url": f"https://www.youtube.com/watch?v={vid}"})
    return out


def _tokens(s):
    return {w for w in re.findall(r"[a-z0-9]{3,}", s.lower())}


def already_covered(topic, titles):
    """True if the library already holds the same subject (loose token overlap)."""
    want = _tokens(topic)
    if not want:
        return True
    for other in titles:
        have = _tokens(other)
        if not have:
            continue
        ov = len(want & have) / max(1, min(len(want), len(have)))
        if ov >= 0.6:
            return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--limit", type=int, default=15)
    a = ap.parse_args()

    lib = json.load(open(LIBRARY)) if os.path.exists(LIBRARY) else {"entries": []}
    entries = lib.get("entries", [])
    seen = json.load(open(SEEN)) if os.path.exists(SEEN) else {"videos": {}}
    titles = [e.get("title", "") for e in entries]

    added, skipped = [], 0
    try:
        feed = fetch_feed(a.limit)
    except Exception as e:
        print("mirror: feed fetch failed:", str(e)[:120])
        return 1
    for v in feed:
        if v["videoId"] in seen["videos"]:
            continue
        topic = clean_topic(v["title"])
        if already_covered(topic, titles):
            seen["videos"][v["videoId"]] = {"skipped": "already covered", "title": v["title"]}
            skipped += 1
            continue
        entry = {
            "id": slug(topic, v["published"] or dt.date.today().isoformat()),
            "title": topic,
            "demand_evidence": (
                f"Reference channel AI Revolution (@airevolutionx) published "
                f"\"{v['title']}\" on {v['published']} ({v['url']}). Same subject, "
                f"proven demand in our niche; we produce our own original script "
                f"and footage, they keep theirs."),
            "verified_sources": [v["url"]],
            "status": "pending",
            "origin": "reference_mirror",
            "reference_video": v["videoId"],
            "added": dt.date.today().isoformat(),
        }
        entries.append(entry)
        titles.append(topic)
        added.append(entry)
        seen["videos"][v["videoId"]] = {"title": v["title"], "topic": topic,
                                        "queued": entry["id"]}
    seen["checked"] = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")

    print(f"mirror: {len(feed)} recent uploads, {len(added)} new topics, {skipped} already covered")
    for e in added:
        print("  +", e["title"][:78])
    if a.dry_run:
        return 0
    if added:
        lib["entries"] = entries
        json.dump(lib, open(LIBRARY, "w"), indent=1, ensure_ascii=False)
    json.dump(seen, open(SEEN, "w"), indent=1, ensure_ascii=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
